"""Builds content/source/inventory.json: what each section of the April 2015 draft contains.

For every section: its numbered equations, its named examples, the figures whose captions it holds, and its
approximate length in words. Only numbers and counts are recorded, never the book's text.
The coverage report and the validator compare the app's content against this inventory.

Usage (from the repository root): python -I tools/build_inventory.py
Reads content/_extracted/sutton-barto-2015.txt (the local, git-ignored text layer) and content/source/sources.json.
"""
import json, re, sys, unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = json.loads((ROOT / "content/source/sources.json").read_text(encoding="utf-8"))["sb"]
OFF = SRC["pdfPageOffset"]
# NFKC undoes the ligatures of the text layer (ﬁ, ﬀ, ﬃ), which otherwise hide some headings.
TEXT = unicodedata.normalize("NFKC", (ROOT / "content/_extracted/sutton-barto-2015.txt").read_text(encoding="utf-8"))

# The text layer as (printed page, line) pairs.
lines = []
for m in re.finditer(r"=====PAGE (\d+)=====\n(.*?)(?======PAGE |\Z)", TEXT, re.S):
    printed = int(m.group(1)) - OFF
    lines += [(printed, ln) for ln in m.group(2).split("\n")]

def find_heading(sec, after):
    """Index of the line holding a section number ("3.8" or "∗3.8") followed by its title, at or after `after`."""
    sid, first = sec["id"], re.sub(r"[^\w]", "", sec["title"].split()[0])[:6]
    for i in range(after, len(lines)):
        p, ln = lines[i]
        if p < sec["page"]:
            continue
        if p > sec["page"] + 1:
            break
        s = ln.strip().lstrip("∗*")
        if s == sid or s.startswith(sid + " "):
            rest = (s[len(sid):] + " " + " ".join(l for _, l in lines[i + 1 : i + 3]))
            if first.lower() in re.sub(r"[^\w]", "", rest).lower():
                return i
    return None

EQ = re.compile(r"\((\d{1,2})\.(\d{1,2})\)\s*$")
EX = re.compile(r"^Example (\d{1,2})\.(\d{1,2})[:\s]\s*(.*)$")
FIG = re.compile(r"^Figure (\d{1,2})\.(\d{1,2}):")
WORD = re.compile(r"[A-Za-z]{2,}")

out = {"$comment": "Generated by tools/build_inventory.py from the text layer of the April 2015 draft. Do not edit by hand.", "source": "sb", "chapters": []}
missing = []
for ch in SRC["chapters"]:
    secs = ch["sections"]
    starts = []
    pos = 0
    for s in secs:
        i = find_heading(s, pos)
        if i is None:
            missing.append(s["id"])
            i = next(k for k in range(pos, len(lines)) if lines[k][0] >= s["page"])
        starts.append(i)
        pos = i + 1
    # A chapter ends where the next chapter's first page begins.
    end_line = next((k for k, (p, _) in enumerate(lines) if p > ch["endPage"]), len(lines))
    begin = next(k for k, (p, _) in enumerate(lines) if p >= ch["startPage"])
    entry = {"id": ch["id"]}
    last_eq = 0
    dedup = lambda xs: list(dict.fromkeys(xs))

    def scan(a, b):
        global last_eq
        eqs, exs, figs = [], [], []
        for _, ln in lines[a:b]:
            # Equations are numbered in order through a chapter; a smaller number at a line end is a later citation.
            if (m := EQ.search(ln)) and m.group(1) == ch["id"] and int(m.group(2)) > last_eq:
                last_eq = int(m.group(2))
                eqs.append(f"{m.group(1)}.{m.group(2)}")
            if (m := EX.match(ln.strip())) and m.group(1) == ch["id"]:
                exs.append(f"{m.group(1)}.{m.group(2)}")
            if (m := FIG.match(ln.strip())) and m.group(1) == ch["id"]:
                figs.append(f"{m.group(1)}.{m.group(2)}")
        return {"words": len(WORD.findall(" ".join(ln for _, ln in lines[a:b]))), "equations": dedup(eqs), "examples": dedup(exs), "figures": dedup(figs)}

    # The chapter's opening text, before its first section heading (Chapter 4's (4.1)-(4.2) are there).
    entry["intro"] = scan(begin, starts[0] if secs else end_line)
    entry["sections"] = [{"id": s["id"], **scan(starts[j], starts[j + 1] if j + 1 < len(secs) else end_line)} for j, s in enumerate(secs)]
    out["chapters"].append(entry)

(ROOT / "content/source/inventory.json").write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8", newline="\n")
tot = lambda k: sum(len(s[k]) for c in out["chapters"] for s in [c["intro"], *c["sections"]])
print(f"inventory: {sum(len(c['sections']) for c in out['chapters'])} sections, {tot('equations')} equations, {tot('examples')} examples, {tot('figures')} figure captions")
if missing:
    print("headings not found (section start taken from its page):", ", ".join(missing))
