// Writes the coverage report: docs/coverage/README.md (all chapters) and docs/coverage/chNN.md (one per chapter).
// Usage (from app/): npm run coverage          regenerate the report
//                    npm run coverage -- --check  fail if the committed report is out of date (part of npm run check)
// Everything is computed by app/src/content/coverage.ts from the content, the source inventory and the declarations;
// nothing in the report is typed by hand.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { loadBundle, loadCoverageInputs } from "./content_loader.ts";
import { computeCoverage, type ChapterCoverage, type SectionCoverage } from "../app/src/content/coverage.ts";

const OUT = resolve(import.meta.dirname, "..", "docs", "coverage");
const b = loadBundle();
const { inventory, declarations } = loadCoverageInputs();
const cov = computeCoverage(b, inventory, declarations);

const LABEL: Record<SectionCoverage["status"], string> = { covered: "covered", partial: "partial", "not-started": "not started", unwritten: "unwritten in the draft" };
const file = (c: ChapterCoverage) => `ch${c.id.padStart(2, "0")}.md`;
const list = (xs: string[], f = (x: string) => x) => (xs.length ? xs.map(f).join(", ") : "–");
const count = (c: ChapterCoverage, s: SectionCoverage["status"]) => c.sections.filter((x) => x.status === s).length;

function chapterPage(c: ChapterCoverage): string {
  const out = [`# Chapter ${c.id}: ${c.title}`, "", `Coverage report, generated by \`npm run coverage\` from the content, \`content/source/inventory.json\` and \`content/coverage/coverage.json\`. Do not edit by hand.`, ""];
  if (c.unwritten) return [...out, "**Unwritten in the April 2015 draft** (title page only). Nothing to cover.", ""].join("\n");
  const written = c.sections.filter((s) => s.status !== "unwritten");
  out.push(`**Status: ${LABEL[c.status]}.** ${count(c, "covered")} of ${written.length} written sections covered, ${count(c, "partial")} partial, ${count(c, "not-started")} not started${c.sections.length > written.length ? `; ${c.sections.length - written.length} heading only in the draft` : ""}.`, "");
  out.push("| § | Title | Status | Lesson | Equations | Examples | Questions | Still needed |", "|---|---|---|---|---|---|---|---|");
  const i = c.intro;
  if (i.equations.expected.length || i.examples.expected.length)
    out.push(`| – | Chapter introduction (before §${c.sections[0]?.id ?? "–"}) | ${i.missing.length ? "partial" : "covered"} | taught in the first section | ${i.equations.expected.length ? `${i.equations.present.length} of ${i.equations.expected.length}` : "–"} | ${i.examples.expected.length ? `${i.examples.asItems.length + i.examples.byLabCheck.length} of ${i.examples.expected.length}` : "–"} | – | ${list(i.missing.map((m) => m.replace("introduction: ", "")))} |`);
  for (const s of c.sections) {
    const eq = s.equations.expected.length ? `${s.equations.present.length} of ${s.equations.expected.length}` : "–";
    const ex = s.examples.expected.length ? `${s.examples.asItems.length + s.examples.byLabCheck.length} of ${s.examples.expected.length}` : "–";
    const lesson = s.lessonLayers.length ? `${s.lessonLayers.length} layers` : "–";
    const tags = [s.treatment === "reading-guide" ? "reading guide" : "", s.thin ? "thin in the draft" : ""].filter(Boolean).join("; ");
    out.push(`| ${s.id} | ${s.title}${tags ? ` (${tags})` : ""} | ${LABEL[s.status]} | ${lesson} | ${eq} | ${ex} | ${s.questions || "–"} | ${s.status === "unwritten" ? "–" : list(s.missing)} |`);
  }
  out.push("", "## Exercises", "");
  const e = c.exercises;
  if (!e.total) out.push("The draft has no exercises in this chapter.");
  else {
    out.push(`${e.total} in the draft: ${e.inBank.length} in the question bank (${list(e.inBank, (x) => "Exercise " + x)}).`);
    const decl = Object.entries(e.declared);
    if (decl.length) out.push("", ...decl.map(([id, d]) => `- Exercise ${id}: ${d === "placeholder" ? "a placeholder in the draft (no exercise text)" : "a guided lab task"}.`));
    out.push("", `Not yet incorporated: ${list(e.missing, (x) => "Exercise " + x)}.`);
  }
  const notes = c.sections.filter((s) => s.thin || s.note);
  if (notes.length) out.push("", "## Notes", "", ...notes.map((s) => `- §${s.id}: ${[s.thin, s.note].filter(Boolean).join(" ")}`));
  const examplesByCheck = c.sections.flatMap((s) => s.examples.byLabCheck);
  if (examplesByCheck.length) out.push("", `Examples reproduced by a lab check rather than a worked-example item: ${list(examplesByCheck, (x) => "Example " + x)} (see \`content/coverage/coverage.json\`).`);
  return out.join("\n") + "\n";
}

function summaryPage(): string {
  const out = ["# Coverage of the April 2015 draft", "", "Generated by `npm run coverage`; `npm run check` fails if this report is out of date. A section is **covered** only when it has a lesson, every numbered equation it contains, every named example it contains (as a worked example or a lab check), and at least one question. A chapter is covered when all its written sections are, and every exercise is in the bank or declared (a placeholder, or a guided lab task).", ""];
  out.push("| Chapter | Status | Sections covered | Partial | Not started | Equations | Examples | Exercises incorporated |", "|---|---|---|---|---|---|---|---|");
  const tot = { s: 0, cov: 0, eqE: 0, eqP: 0, exE: 0, exP: 0, xT: 0, xI: 0 };
  for (const c of cov) {
    const w = c.sections.filter((s) => s.status !== "unwritten");
    const parts = [c.intro, ...w];
    const eqE = parts.reduce((n, s) => n + s.equations.expected.length, 0), eqP = parts.reduce((n, s) => n + s.equations.present.length, 0);
    const exE = parts.reduce((n, s) => n + s.examples.expected.length, 0), exP = parts.reduce((n, s) => n + s.examples.asItems.length + s.examples.byLabCheck.length, 0);
    const xI = c.exercises.inBank.length + Object.keys(c.exercises.declared).length;
    Object.assign(tot, { s: tot.s + w.length, cov: tot.cov + count(c, "covered"), eqE: tot.eqE + eqE, eqP: tot.eqP + eqP, exE: tot.exE + exE, exP: tot.exP + exP, xT: tot.xT + c.exercises.total, xI: tot.xI + xI });
    out.push(c.unwritten
      ? `| [${c.id}. ${c.title}](${file(c)}) | unwritten in the draft | – | – | – | – | – | – |`
      : `| [${c.id}. ${c.title}](${file(c)}) | ${LABEL[c.status]} | ${count(c, "covered")} of ${w.length} | ${count(c, "partial")} | ${count(c, "not-started")} | ${eqP} of ${eqE} | ${exP} of ${exE} | ${c.exercises.total ? `${xI} of ${c.exercises.total}` : "–"} |`);
  }
  out.push(`| **All** | | **${tot.cov} of ${tot.s}** | | | **${tot.eqP} of ${tot.eqE}** | **${tot.exP} of ${tot.exE}** | **${tot.xI} of ${tot.xT}** |`);
  return out.join("\n") + "\n";
}

const pages: Record<string, string> = { "README.md": summaryPage(), ...Object.fromEntries(cov.map((c) => [file(c), chapterPage(c)])) };
if (process.argv.includes("--check")) {
  const stale = Object.entries(pages).filter(([f, text]) => !existsSync(join(OUT, f)) || readFileSync(join(OUT, f), "utf-8").replace(/\r\n/g, "\n") !== text);
  const extra = existsSync(OUT) ? readdirSync(OUT).filter((f) => !(f in pages)) : [];
  if (stale.length || extra.length) {
    console.error(`coverage report out of date: ${[...stale.map(([f]) => f), ...extra.map((f) => f + " (no longer generated)")].join(", ")}. Run npm run coverage.`);
    process.exit(1);
  }
  console.log(`coverage report up to date (${Object.keys(pages).length} files).`);
} else {
  mkdirSync(OUT, { recursive: true });
  for (const [f, text] of Object.entries(pages)) writeFileSync(join(OUT, f), text, "utf-8");
  console.log(`wrote docs/coverage/: ${Object.keys(pages).length} files.`);
}
