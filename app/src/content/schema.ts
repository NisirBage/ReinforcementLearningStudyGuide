export const SUP_UNIT = /^sup-[a-z0-9]+(-[a-z0-9]+)*$/;
const SLUG = "[a-z0-9]+(?:-[a-z0-9]+)*";
const UNIT = "(?:ch(?:0[1-9]|1[0-5])|sup-[a-z0-9]+(?:-[a-z0-9]+)*)";
export const CONCEPT_ID = new RegExp(`^${UNIT}\\.${SLUG}$`); // "ch02.incremental-update"
const itemId = (prefix: string) => new RegExp(`^${prefix}\\.${UNIT}\\.${SLUG}$`); // "eq.ch02.incremental-update"
export const isSupplementaryUnit = (u: string): boolean => u.startsWith("sup-");

