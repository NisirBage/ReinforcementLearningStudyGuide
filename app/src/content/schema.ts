export type SourceRef =
  | { kind: "textbook"; chapter: string; section?: string; printedPages: [number, number]; pdfPages: [number, number] }
  | { kind: "textbook-matter"; matter: string; printedPages: [string, string]; pdfPages: [number, number] }
  | { kind: "zhao"; chapter: string; section?: string; printedPages: [number, number]; pdfPages: [number, number] }
  | { kind: "lecture"; lecture: string; slides: [number, number] }
  | { kind: "paper"; citation: string };

export const SOURCE_KINDS = ["textbook", "textbook-matter", "zhao", "lecture", "paper"] as const;
export const CORE_KINDS = ["textbook", "textbook-matter"] as const;

export const FLAG_TYPES = [
  "suspected-typo", // the printed text looks wrong; the transcription keeps it and `suggestion` says what was probably meant
  "source-acknowledged-issue", // the book itself points out a problem (e.g. the bug noted under Fig. 4.3)
  "figure-rounding", // printed numbers are rounded/truncated; tests compare at that precision
  "extraction-uncertain", // the text layer was garbled; the page image was used, worth a second look
  "empty-in-draft", // the draft has a heading but no content
  "notation-unverified", // 2018-edition notation given from general knowledge; no copy of that edition was checked
] as const;
export type FlagType = (typeof FLAG_TYPES)[number];
