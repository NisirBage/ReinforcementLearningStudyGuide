// Content schema for the RL Study Lab, plus a dependency-free validator.
// Shared by the app, tools/validate_content.ts and the tests, so it stays pure TypeScript (no browser or Node APIs).
//
// Source policy (docs/DECISION_LOG.md D-021, D-022):
//   CORE          Sutton & Barto, 2nd ed. draft of April 2015 ("textbook"). Authoritative for the syllabus and notation.
//   SUPPLEMENTARY Zhao's book, Zhao's lectures, papers. Always labelled; attached to a core location; never part of
//                 the core syllabus. Core content may not cite them or depend on them.
// Every textbook reference carries chapter, optional section, printed pages and PDF pages (PDF = printed + 14).
// Questionable source material is flagged, never silently corrected: the transcription stays as printed.

// ---------- Source registry (content/source/sources.json, generated by tools/build_sources.py) ----------

export interface SectionEntry {
  id: string; // "7.4" or "7.4.2"
  title: string;
  page: number | null;
  level: "section" | "subsection";
  optional: boolean; // marked ∗ in the book
}

export interface ChapterEntry {
  id: string; // "7", or "A".."D" for Zhao's appendices
  title: string;
  part: string | null;
  startPage: number;
  endPage: number;
  sections: SectionEntry[];
  pdf?: { file: string; offset: number; pages: number }; // Zhao: one PDF per chapter, printed = PDF + offset
}

export interface BookSource {
  key: "sb" | "zhao";
  role: "core" | "supplementary";
  title: string;
  authors: string;
  edition: string;
  pdfPageOffset: number | null; // single-file books: PDF page = printed page + offset
  parts: { label: string; title: string; page: number | null }[];
  chapters: ChapterEntry[];
  matter: { title: string; page: string; pdfPage?: number }[];
}

export interface LectureEntry {
  id: string; // "L7"
  number: number;
  title: string;
  slides: number;
  zhaoChapter: string;
}

export interface Sources {
  sb: BookSource;
  zhao: BookSource;
  lectures: { key: "lectures"; role: "supplementary"; title: string; authors: string; items: LectureEntry[] };
}

