// ---------- Validation helpers ----------

type Obj = Record<string, unknown>;
const isObj = (v: unknown): v is Obj => typeof v === "object" && v !== null && !Array.isArray(v);
const isStr = (v: unknown): v is string => typeof v === "string" && v.trim().length > 0;
const isInt = (v: unknown): v is number => Number.isInteger(v);
const isNum = (v: unknown): v is number => typeof v === "number" && Number.isFinite(v);
const oneOf = <T extends readonly string[]>(list: T, v: unknown): v is T[number] => typeof v === "string" && (list as readonly string[]).includes(v);
const strArr = (v: unknown): v is string[] => Array.isArray(v) && v.every(isStr);
const pair = (v: unknown): v is [number, number] => Array.isArray(v) && v.length === 2 && isInt(v[0]) && isInt(v[1]) && v[0] <= v[1];

export function findChapter(src: Sources, book: "sb" | "zhao", id: string): ChapterEntry | undefined {
  return src[book].chapters.find((c) => c.id === id);
}
export function findSection(src: Sources, book: "sb" | "zhao", id: string): SectionEntry | undefined {
  return src[book].chapters.find((c) => id.startsWith(c.id + "."))?.sections.find((s) => s.id === id);
}

/** Printed page range of a section: from its page to the page before the next same-or-higher-level entry. */
export function sectionPages(src: Sources, book: "sb" | "zhao", id: string): [number, number] | undefined {
  const ch = src[book].chapters.find((c) => id.startsWith(c.id + "."));
  if (!ch) return undefined;
  const i = ch.sections.findIndex((s) => s.id === id);
  const s = ch.sections[i];
  if (!s || s.page === null) return undefined;
  const next = ch.sections.slice(i + 1).find((x) => !x.id.startsWith(id + ".") && x.page !== null);
  // The next section may start on the same page as this one ends.
  return [s.page, next ? Math.max(s.page, next.page!) : ch.endPage];
}

/** Lower-case roman numeral to integer, or null if it is not one. */
export function romanToInt(s: string): number | null {
  if (!/^[ivxlc]+$/.test(s)) return null;
  const val: Record<string, number> = { i: 1, v: 5, x: 10, l: 50, c: 100 };
  let total = 0;
  for (let i = 0; i < s.length; i++) total += val[s[i]] < (val[s[i + 1]] ?? 0) ? -val[s[i]] : val[s[i]];
  return total;
}

export function pdfPageOf(src: Sources, book: "sb" | "zhao", chapter: string, printed: number): number | undefined {
  if (book === "sb") return src.sb.pdfPageOffset === null ? undefined : printed + src.sb.pdfPageOffset;
  const pdf = findChapter(src, "zhao", chapter)?.pdf;
  return pdf ? printed - pdf.offset : undefined;
}

function validateBook(b: unknown, key: "sb" | "zhao"): string[] {
  const errs: string[] = [];
  if (!isObj(b)) return [`sources.${key}: missing`];
  if (b.role !== (key === "sb" ? "core" : "supplementary")) errs.push(`sources.${key}: role must be ${key === "sb" ? "core" : "supplementary"}`);
  if (!Array.isArray(b.chapters) || b.chapters.length === 0) return [...errs, `sources.${key}: no chapters`];
  const ids = new Set<string>();
  let lastStart = 0;
  b.chapters.forEach((c: unknown, i) => {
    const at = `sources.${key}.chapters[${i}]`;
    if (!isObj(c)) return errs.push(`${at} not an object`);
    if (!isStr(c.id) || ids.has(c.id)) errs.push(`${at} id missing or duplicate`);
    else ids.add(c.id);
    if (!isInt(c.startPage) || !isInt(c.endPage) || c.startPage > c.endPage) errs.push(`${at} bad page range`);
    else if (c.startPage <= lastStart) errs.push(`${at} starts before the previous chapter`);
    else lastStart = c.startPage;
    if (key === "zhao") {
      const p = c.pdf;
      if (!isObj(p) || !isStr(p.file) || !isInt(p.offset) || !isInt(p.pages)) errs.push(`${at} needs pdf {file, offset, pages}`);
      else if (isInt(c.startPage) && isInt(c.endPage) && (c.startPage - p.offset < 1 || c.endPage - p.offset > p.pages)) errs.push(`${at} pages fall outside its PDF file`);
    }
    if (!Array.isArray(c.sections)) return errs.push(`${at} sections must be an array`);
    let lastPage = isInt(c.startPage) ? c.startPage : 0;
    const secIds = new Set<string>();
    c.sections.forEach((s: unknown, j) => {
      const sat = `${at}.sections[${j}]`;
      if (!isObj(s)) return errs.push(`${sat} not an object`);
      if (!isStr(s.id) || !s.id.startsWith(`${String(c.id)}.`) || secIds.has(s.id)) errs.push(`${sat} id must be unique and start with "${String(c.id)}."`);
      else secIds.add(s.id);
      if (s.page !== null && (!isInt(s.page) || s.page < lastPage || (isInt(c.endPage) && s.page > c.endPage))) errs.push(`${sat} page out of order or outside the chapter`);
      else if (isInt(s.page)) lastPage = s.page;
    });
  });
  return errs;
}

export function validateSources(data: unknown): string[] {
  if (!isObj(data)) return ["sources: not an object"];
  const errs = [...validateBook(data.sb, "sb"), ...validateBook(data.zhao, "zhao")];
  if (isObj(data.sb) && data.sb.pdfPageOffset !== 14) errs.push("sources.sb: pdfPageOffset must be 14 for the April 2015 draft");
  if (isObj(data.sb) && Array.isArray(data.sb.chapters)) {
    const ex = data.sb.exercises;
    const chapters = data.sb.chapters as ChapterEntry[];
    if (!Array.isArray(ex)) errs.push("sources.sb.exercises must be an array (run tools/build_sources.py)");
    else {
      const seen = new Set<string>();
      ex.forEach((e: unknown, i) => {
        const at = `sources.sb.exercises[${i}]`;
        if (!isObj(e) || !isStr(e.id) || !/^\d+\.\d+$/.test(e.id) || seen.has(e.id)) return errs.push(`${at} needs a unique id N.M`);
        seen.add(e.id);
        const ch = chapters.find((c) => c.id === e.chapter);
        if (!ch || !e.id.startsWith(`${ch.id}.`)) return errs.push(`${at} chapter must match its number`);
        if (!isInt(e.page) || e.page < ch.startPage || e.page > ch.endPage) errs.push(`${at} page outside chapter ${ch.id}`);
        else if (e.pdfPage !== e.page + 14) errs.push(`${at} pdfPage must be page + 14`);
        if (typeof e.optional !== "boolean" || typeof e.programming !== "boolean" || typeof e.placeholder !== "boolean") errs.push(`${at} optional, programming and placeholder must be booleans`);
      });
    }
  }
  const lec = data.lectures;
  if (!isObj(lec) || !Array.isArray(lec.items) || lec.items.length === 0) return [...errs, "sources.lectures: missing items"];
  lec.items.forEach((l: unknown, i) => {
    if (!isObj(l) || l.id !== `L${String(l.number)}` || !isInt(l.slides) || l.slides < 1) errs.push(`sources.lectures.items[${i}] invalid`);
  });
  return errs;
}

export function validateCurriculum(data: unknown, src: Sources): string[] {
  if (!isObj(data)) return ["curriculum: not an object"];
  const errs: string[] = [];
  const ids = new Set<string>();
  if (!Array.isArray(data.core)) return ["curriculum.core must be an array"];
  const chapters = new Set(src.sb.chapters.map((c) => c.id));
  const covered = new Set<string>();
  data.core.forEach((u: unknown, i) => {
    const at = `curriculum.core[${i}]`;
    if (!isObj(u) || !isStr(u.id) || !CORE_UNIT.test(u.id) || ids.has(u.id)) return errs.push(`${at} needs a unique id ch01..ch15`);
    ids.add(u.id);
    if (!isStr(u.chapter) || !chapters.has(u.chapter)) errs.push(`${at} unknown textbook chapter`);
    else {
      covered.add(u.chapter);
      if (u.id !== `ch${u.chapter.padStart(2, "0")}`) errs.push(`${at} id must match its chapter`);
      if (u.title !== findChapter(src, "sb", u.chapter)!.title) errs.push(`${at} title must match the textbook chapter title`);
    }
    if (u.status !== "core" && u.status !== "empty-in-draft") errs.push(`${at} bad status`);
  });
  for (const c of chapters) if (!covered.has(c)) errs.push(`curriculum.core omits textbook chapter ${c}`);
  if (!Array.isArray(data.supplementary)) return [...errs, "curriculum.supplementary must be an array"];
  const lectures = new Set(src.lectures.items.map((l) => l.id));
  data.supplementary.forEach((u: unknown, i) => {
    const at = `curriculum.supplementary[${i}]`;
    if (!isObj(u) || !isStr(u.id) || !SUP_UNIT.test(u.id) || ids.has(u.id)) return errs.push(`${at} needs a unique sup- id`);
    ids.add(u.id);
    if (!isStr(u.title)) errs.push(`${at} title missing`);
    const a = u.attachTo;
    if (!isObj(a) || !isStr(a.chapter) || !findChapter(src, "sb", a.chapter) || (a.section !== undefined && !(isStr(a.section) && findSection(src, "sb", a.section))))
      errs.push(`${at} attachTo must name a textbook chapter or section`);
    const z = u.zhao ?? [];
    const l = u.lectures ?? [];
    const p = u.papers ?? [];
    if (!strArr(z) || !z.every((c) => findChapter(src, "zhao", c))) errs.push(`${at} unknown Zhao chapter`);
    if (!strArr(l) || !l.every((x) => lectures.has(x))) errs.push(`${at} unknown lecture`);
    if (!strArr(p)) errs.push(`${at} papers must be strings`);
    if (strArr(z) && strArr(l) && strArr(p) && z.length + l.length + p.length === 0) errs.push(`${at} must name its supplementary source`);
  });
  if (!Array.isArray(data.emptyInSource)) errs.push("curriculum.emptyInSource must be an array");
  else
    data.emptyInSource.forEach((e: unknown, i) => {
      if (!isObj(e) || !isStr(e.chapter) || !findChapter(src, "sb", e.chapter) || (e.section !== null && !(isStr(e.section) && findSection(src, "sb", e.section))) || !isStr(e.note))
        errs.push(`curriculum.emptyInSource[${i}] must name a textbook chapter or section and a note`);
    });
  return errs;
}

/** Checks one source reference, including exact printed-to-PDF page consistency. */
export function validateSourceRef(r: unknown, at: string, src: Sources): string[] {
  if (!isObj(r) || !oneOf(SOURCE_KINDS, r.kind)) return [`${at} bad source kind`];
  switch (r.kind) {
    case "paper":
      return isStr(r.citation) ? [] : [`${at} paper needs a citation`];
    case "lecture": {
      const lec = src.lectures.items.find((l) => l.id === r.lecture);
      if (!lec) return [`${at} unknown lecture ${String(r.lecture)}`];
      return pair(r.slides) && r.slides[0] >= 1 && r.slides[1] <= lec.slides ? [] : [`${at} slides must be [start, end] within 1–${lec.slides}`];
    }
    case "textbook-matter": {
      // Front matter is numbered in roman numerals (PDF page = numeral value); back matter continues the arabic pages.
      const i = src.sb.matter.findIndex((x) => x.title === r.matter);
      const m = src.sb.matter[i];
      if (!m || m.pdfPage === undefined) return [`${at} unknown front/back matter ${String(r.matter)}`];
      const pp = r.printedPages;
      if (!Array.isArray(pp) || pp.length !== 2 || !pp.every(isStr)) return [`${at} printedPages must be two page labels`];
      const toPdf = (label: string) => (/^\d+$/.test(label) ? Number(label) + (src.sb.pdfPageOffset ?? 0) : romanToInt(label));
      const start = m.pdfPage;
      const next = src.sb.matter[i + 1]?.pdfPage;
      const end = (next !== undefined && next > start ? next - 1 : start + 50);
      const want = pp.map(toPdf);
      if (want.some((x) => x === null || x < start || x > end) || want[0]! > want[1]!) return [`${at} printed pages ${pp.join("–")} are not inside "${m.title}"`];
      return pair(r.pdfPages) && r.pdfPages[0] === want[0] && r.pdfPages[1] === want[1] ? [] : [`${at} pdfPages must be ${want.join("–")} for printed ${pp.join("–")}`];
    }
    case "textbook":
    case "zhao": {
      const book = r.kind === "textbook" ? "sb" : "zhao";
      const name = book === "sb" ? "textbook" : "Zhao";
      const ch = isStr(r.chapter) ? findChapter(src, book, r.chapter) : undefined;
      if (!ch) return [`${at} unknown ${name} chapter ${String(r.chapter)}`];
      if (!pair(r.printedPages) || !pair(r.pdfPages)) return [`${at} printedPages and pdfPages must both be [start, end]`];
      const [a, b] = r.printedPages;
      if (a < ch.startPage || b > ch.endPage) return [`${at} printed pages ${a}–${b} outside ${name} chapter ${ch.id} (${ch.startPage}–${ch.endPage})`];
      const want: [number, number] = [pdfPageOf(src, book, ch.id, a)!, pdfPageOf(src, book, ch.id, b)!];
      if (r.pdfPages[0] !== want[0] || r.pdfPages[1] !== want[1]) return [`${at} pdfPages ${r.pdfPages.join("–")} do not match printed ${a}–${b} (expected ${want.join("–")})`];
      if (r.section !== undefined) {
        if (!isStr(r.section) || !r.section.startsWith(ch.id + ".") || !findSection(src, book, r.section)) return [`${at} unknown ${name} section ${String(r.section)}`];
        const span = sectionPages(src, book, r.section);
        if (span && (a < span[0] || b > span[1])) return [`${at} printed pages ${a}–${b} outside §${r.section} (${span[0]}–${span[1]})`];
      }
      return [];
    }
  }
  return [];
}

/** Core items cite only the textbook; supplementary items cite only supplementary sources. */
function validateSourceList(v: unknown, at: string, src: Sources, unit: unknown): string[] {
  if (!Array.isArray(v) || v.length === 0) return [`${at} needs at least one source`];
  const errs = v.flatMap((r, i) => validateSourceRef(r, `${at}[${i}]`, src));
  const kinds = v.filter(isObj).map((r) => r.kind as string);
  const core = (CORE_KINDS as readonly string[]);
  if (isStr(unit) && isSupplementaryUnit(unit)) {
    if (kinds.some((k) => core.includes(k))) errs.push(`${at} supplementary items must not cite the textbook as their source (link through the unit's attachTo instead)`);
  } else if (kinds.some((k) => !core.includes(k))) errs.push(`${at} core items may cite only the April 2015 textbook`);
  return errs;
}

function validateFlags(v: unknown, at: string): string[] {
  if (v === undefined) return [];
  if (!Array.isArray(v)) return [`${at} flags must be an array`];
  return v.flatMap((f, i) => (isObj(f) && oneOf(FLAG_TYPES, f.type) && isStr(f.note) && (f.suggestion === undefined || isStr(f.suggestion)) ? [] : [`${at}.flags[${i}] needs a known type and a note`]));
}

function validateVerification(v: unknown, at: string, checks: Set<string>, required: boolean): string[] {
  if (v === undefined) return required ? [`${at} needs a verification record`] : [];
  if (!isObj(v) || !oneOf(VERIFY_METHODS, v.method) || !isStr(v.on) || !/^\d{4}-\d{2}-\d{2}$/.test(v.on)) return [`${at} verification needs method and ISO date`];
  if (v.method === "computed" && !(isStr(v.check) && checks.has(v.check))) return [`${at} computed verification must name an existing check (got ${String(v.check)})`];
  return [];
}

// ---------- Whole-bundle validation ----------

export interface ValidationContext {
  checks: Set<string>; // ids exported by app/src/content/checks.ts
  implementations: Set<string>; // keys of app/src/lib/rl/registry.ts
}

export function validateBundle(b: ContentBundle, ctx: ValidationContext): string[] {
  const errs = validateSources(b.sources);
  if (errs.length) return errs; // everything else depends on the registry
  const src = b.sources;
  errs.push(...validateCurriculum(b.curriculum, src));
  if (errs.length) return errs;
  const units = new Set([...b.curriculum.core.map((u) => u.id), ...b.curriculum.supplementary.map((u) => u.id)]);
  const unitOk = (u: unknown, at: string) => (isStr(u) && units.has(u) ? [] : [`${at} unknown unit ${String(u)}`]);

  // Notation
  const notIds = new Set<string>();
  b.notation.forEach((n, i) => {
    const at = `notation[${i}]`;
    if (!isStr(n.id) || notIds.has(n.id)) errs.push(`${at} id missing or duplicate`);
    notIds.add(n.id);
    if (!isStr(n.tex) || !isStr(n.meaning)) errs.push(`${at} tex and meaning required`);
    errs.push(...validateSourceList(n.sources, `${at}.sources`, src, "ch01"), ...validateFlags(n.flags, at));
    if (n.tex2018 !== undefined && !(n.flags ?? []).some((f) => f.type === "notation-unverified"))
      errs.push(`${at} a 2018 cross-reference must carry a notation-unverified flag until checked against that edition`);
  });

  // Concepts
  const conceptIds = new Set<string>();
  const conceptUnit = new Map<string, string>();
  b.concepts.forEach((c, i) => {
    const at = `concept ${c?.id ?? i}`;
    if (!isStr(c.id) || !CONCEPT_ID.test(c.id) || conceptIds.has(c.id)) errs.push(`${at}: bad or duplicate id`);
    conceptIds.add(c.id);
    conceptUnit.set(c.id, c.unit);
    errs.push(...unitOk(c.unit, at));
    if (isStr(c.id) && !c.id.startsWith(c.unit + ".")) errs.push(`${at}: id must start with its unit`);
    if (!isStr(c.title) || !isStr(c.summary)) errs.push(`${at}: title and summary required`);
    if (!oneOf(CONCEPT_KINDS, c.kind)) errs.push(`${at}: bad kind`);
    for (const f of ["prereqs", "related", "keywords"] as const) if (!Array.isArray(c[f]) || !c[f].every(isStr)) errs.push(`${at}: ${f} must be a string array`);
    errs.push(...validateSourceList(c.sources, `${at}.sources`, src, c.unit), ...validateFlags(c.flags, at));
  });
  errs.push(...validateConceptGraph(b.concepts));
  // Never merge supplementary material into the core syllabus: a core concept may not require a supplementary one.
  for (const c of b.concepts)
    if (!isSupplementaryUnit(c.unit))
      for (const p of c.prereqs) if (isSupplementaryUnit(conceptUnit.get(p) ?? "")) errs.push(`concept ${c.id}: core concept lists supplementary prerequisite ${p}`);
  const sameSide = (unit: string, concept: string) => isSupplementaryUnit(unit) === isSupplementaryUnit(conceptUnit.get(concept) ?? "");

  const ids = new Set<string>();
  const claim = (id: string, at: string) => {
    if (ids.has(id)) errs.push(`${at}: duplicate id`);
    ids.add(id);
  };

  b.equations.forEach((e, i) => {
    const at = `equation ${e?.id ?? i}`;
    if (!isStr(e.id) || !itemId("eq").test(e.id)) errs.push(`${at}: id must look like eq.<unit>.<slug>`);
    else claim(e.id, at);
    errs.push(...unitOk(e.unit, at));
    if (!conceptIds.has(e.concept)) errs.push(`${at}: unknown concept ${e.concept}`);
    else if (!sameSide(e.unit, e.concept)) errs.push(`${at}: core and supplementary items cannot share a concept`);
    if (!isStr(e.name) || !isStr(e.tex) || !isStr(e.intuition)) errs.push(`${at}: name, tex and intuition required`);
    if (!Array.isArray(e.symbols) || e.symbols.length === 0 || !e.symbols.every((s) => isObj(s) && isStr(s.tex) && isStr(s.meaning))) errs.push(`${at}: every symbol needs tex and meaning`);
    if (!strArr(e.assumptions) || !Array.isArray(e.pitfalls) || !e.pitfalls.every(isStr)) errs.push(`${at}: assumptions and pitfalls must be string arrays`);
    if (e.derivation !== undefined && !(Array.isArray(e.derivation) && e.derivation.length > 0 && e.derivation.every((s) => isObj(s) && isStr(s.tex) && isStr(s.why))))
      errs.push(`${at}: derivation steps need tex and why`);
    if (e.notation2018 !== undefined && !(isStr(e.notation2018.tex) && isStr(e.notation2018.note) && (e.flags ?? []).some((f) => f.type === "notation-unverified")))
      errs.push(`${at}: notation2018 needs tex, note and a notation-unverified flag`);
    // A textbook equation is transcribed from the page image, not the text layer (display maths extracts garbled).
    if (!isSupplementaryUnit(e.unit) && e.verification?.method !== "page-image") errs.push(`${at}: textbook equations must be verified against the page image`);
    errs.push(...validateSourceList(e.sources, `${at}.sources`, src, e.unit), ...validateFlags(e.flags, at), ...validateVerification(e.verification, at, ctx.checks, true));
  });

  b.algorithms.forEach((a, i) => {
    const at = `algorithm ${a?.id ?? i}`;
    if (!isStr(a.id) || !itemId("alg").test(a.id)) errs.push(`${at}: id must look like alg.<unit>.<slug>`);
    else claim(a.id, at);
    errs.push(...unitOk(a.unit, at));
    if (!conceptIds.has(a.concept) || !sameSide(a.unit, a.concept)) errs.push(`${at}: unknown concept or concept on the other side of the core/supplementary line`);
    if (!isStr(a.name) || !strArr(a.inputs) || !isStr(a.output)) errs.push(`${at}: name, inputs and output required`);
    if (!Array.isArray(a.lines) || a.lines.length === 0 || !a.lines.every((l) => isObj(l) && isInt(l.indent) && l.indent >= 0 && isStr(l.text))) errs.push(`${at}: lines need indent and text`);
    if (!ctx.implementations.has(a.implementation)) errs.push(`${at}: implementation ${a.implementation} is not in lib/rl/registry.ts`);
    errs.push(...validateSourceList(a.sources, `${at}.sources`, src, a.unit), ...validateFlags(a.flags, at), ...validateVerification(a.verification, at, ctx.checks, true));
  });
  // Explainers are checked once every equation, algorithm and lab is known.
  const eqUnit = new Map(b.equations.map((e) => [e.id, e.unit]));
  const algIds = new Set(b.algorithms.map((a) => a.id));
  const labSlugs = new Set(b.labs.map((l) => l.slug));
  b.algorithms.forEach((a) => {
    const at = `algorithm ${a.id} explainer`;
    const x = a.explainer as unknown;
    if (!isObj(x)) return errs.push(`${at}: every implemented algorithm needs an explainer`);
    if (!isStr(x.problem)) errs.push(`${at}: problem required`);
    if (!strArr(x.equations) || x.equations.length === 0 || !x.equations.every((id) => eqUnit.has(id) && isSupplementaryUnit(eqUnit.get(id)!) === isSupplementaryUnit(a.unit))) errs.push(`${at}: equations must be known equations on the same side of the core/supplementary line`);
    if (x.derivation !== undefined && !(Array.isArray(x.derivation) && x.derivation.length > 0 && x.derivation.every((s) => isObj(s) && isStr(s.tex) && isStr(s.why)))) errs.push(`${at}: derivation steps need tex and why`);
    if (!isObj(x.example) || !isStr(x.example.text)) errs.push(`${at}: a worked example is required`);
    else if (x.example.check !== undefined && !(isStr(x.example.check) && ctx.checks.has(x.example.check))) errs.push(`${at}: unknown example check ${String(x.example.check)}`);
    if (!oneOf(DEMO_KEYS, x.demo)) errs.push(`${at}: demo must be one of ${DEMO_KEYS.join(", ")}`);
    if (!isStr(x.lab) || !labSlugs.has(x.lab)) errs.push(`${at}: lab must be a lab slug`);
    if (!strArr(x.advantages) || !x.advantages.length || !strArr(x.limitations) || !x.limitations.length) errs.push(`${at}: advantages and limitations required`);
    if (!Array.isArray(x.comparisons) || !x.comparisons.length || !x.comparisons.every((c) => isObj(c) && isStr(c.point) && isStr(c.with) && (algIds.has(c.with) || conceptIds.has(c.with)))) errs.push(`${at}: comparisons need a known algorithm or concept and a point`);
  });

  b.examples.forEach((x, i) => {
    const at = `example ${x?.id ?? i}`;
    if (!isStr(x.id) || !itemId("ex").test(x.id)) errs.push(`${at}: id must look like ex.<unit>.<slug>`);
    else claim(x.id, at);
    errs.push(...unitOk(x.unit, at));
    if (!strArr(x.concepts) || x.concepts.length === 0 || !x.concepts.every((c) => conceptIds.has(c) && sameSide(x.unit, c))) errs.push(`${at}: concepts must exist on the same side of the core/supplementary line`);
    if (!isStr(x.title) || !isStr(x.summary)) errs.push(`${at}: title and summary required`);
    if (!Array.isArray(x.facts) || !x.facts.every((f) => isObj(f) && isStr(f.claim) && isStr(f.check) && ctx.checks.has(f.check))) errs.push(`${at}: every fact needs a claim and an existing check`);
    errs.push(...validateSourceList(x.sources, `${at}.sources`, src, x.unit), ...validateFlags(x.flags, at), ...validateVerification(x.verification, at, ctx.checks, true));
  });

  b.figures.forEach((f, i) => {
    const at = `figure ${f?.id ?? i}`;
    if (!isStr(f.id) || !itemId("fig").test(f.id)) errs.push(`${at}: id must look like fig.<unit>.<slug>`);
    else claim(f.id, at);
    errs.push(...unitOk(f.unit, at));
    if (!strArr(f.concepts) || f.concepts.length === 0 || !f.concepts.every((c) => conceptIds.has(c) && sameSide(f.unit, c))) errs.push(`${at}: concepts must exist on the same side of the core/supplementary line`);
    if (!isStr(f.title) || !isStr(f.caption)) errs.push(`${at}: title and caption required`);
    const s = f.spec as unknown;
    if (!isObj(s)) errs.push(`${at}: spec missing`);
    else if (s.kind === "value-grids") {
      const n = isInt(s.rows) && isInt(s.cols) ? s.rows * s.cols : -1;
      if (n < 1) errs.push(`${at}: rows and cols must be positive integers`);
      if (!Array.isArray(s.terminal) || !s.terminal.every((x) => isInt(x) && x >= 0 && x < n)) errs.push(`${at}: terminal cells must be cell indices`);
      if (!Array.isArray(s.grids) || s.grids.length === 0 || !s.grids.every((g) => isObj(g) && isStr(g.label) && Array.isArray(g.values) && g.values.length === n && g.values.every(isNum)))
        errs.push(`${at}: every grid needs a label and rows × cols numbers`);
      if (s.env !== undefined && s.env !== "gridworld4x4") errs.push(`${at}: unknown env`);
    } else if (s.kind === "backup-diagram") {
      if (s.root !== "state" && s.root !== "action") errs.push(`${at}: root must be state or action`);
      if (!Array.isArray(s.branching) || s.branching.length !== 2 || !s.branching.every((x) => isInt(x) && x >= 1 && x <= 5)) errs.push(`${at}: branching must be two integers 1–5`);
      if (!isObj(s.labels) || !isStr(s.labels.root) || !isStr(s.labels.mid) || !isStr(s.labels.reward) || !isStr(s.labels.leaf)) errs.push(`${at}: labels need root, mid, reward and leaf`);
    } else errs.push(`${at}: unknown figure kind`);
    if (!isSupplementaryUnit(f.unit) && f.verification?.method !== "page-image" && f.verification?.method !== "computed") errs.push(`${at}: textbook figures must be checked against the page image or by computation`);
    errs.push(...validateSourceList(f.sources, `${at}.sources`, src, f.unit), ...validateFlags(f.flags, at), ...validateVerification(f.verification, at, ctx.checks, true));
  });

  const slugs = new Set<string>();
  b.labs.forEach((l, i) => {
    const at = `lab ${l?.id ?? i}`;
    if (!isStr(l.id) || !itemId("lab").test(l.id)) errs.push(`${at}: id must look like lab.<unit>.<slug>`);
    else claim(l.id, at);
    if (!isStr(l.slug) || !/^[a-z0-9]+(-[a-z0-9]+)*$/.test(l.slug) || slugs.has(l.slug)) errs.push(`${at}: slug must be a unique lower-case route segment`);
    else slugs.add(l.slug);
    errs.push(...unitOk(l.unit, at));
    if (!isStr(l.title) || !isStr(l.summary)) errs.push(`${at}: title and summary required`);
    if (!strArr(l.guide) || l.guide.length === 0) errs.push(`${at}: guide needs at least one step`);
    const book = isSupplementaryUnit(l.unit) ? "zhao" : "sb";
    if (!strArr(l.sections) || l.sections.length === 0 || !l.sections.every((s) => findSection(src, book, s))) errs.push(`${at}: sections must be ${book === "sb" ? "textbook" : "Zhao"} sections`);
    if (!strArr(l.concepts) || l.concepts.length === 0 || !l.concepts.every((c) => conceptIds.has(c) && sameSide(l.unit, c))) errs.push(`${at}: concepts must exist on the same side of the core/supplementary line`);
    if (!strArr(l.implementations) || l.implementations.length === 0 || !l.implementations.every((k) => ctx.implementations.has(k))) errs.push(`${at}: every implementation must be in lib/rl/registry.ts`);
    if (l.verification?.method !== "computed") errs.push(`${at}: a lab must be verified by a computed check that reproduces the source`);
    if (l.checks !== undefined && !(strArr(l.checks) && l.checks.every((c) => ctx.checks.has(c)))) errs.push(`${at}: unknown check in checks`);
    errs.push(...validateSourceList(l.sources, `${at}.sources`, src, l.unit), ...validateFlags(l.flags, at), ...validateVerification(l.verification, at, ctx.checks, true));
  });

  const refIds = ids; // equations, algorithms, examples and figures that lesson layers may show
  b.lessons.forEach((l, i) => {
    const at = `lesson ${l?.unit ?? i}`;
    errs.push(...unitOk(l.unit, at));
    if (!Array.isArray(l.sections) || l.sections.length === 0) return errs.push(`${at}: no sections`);
    const secIds = new Set<string>();
    l.sections.forEach((s, j) => {
      const sat = `${at}.sections[${j}]`;
      if (!isStr(s.id) || !s.id.startsWith(l.unit + ".") || secIds.has(s.id)) errs.push(`${sat}: id must be unique and start with the unit`);
      secIds.add(s.id);
      const book = isSupplementaryUnit(l.unit) ? "zhao" : "sb";
      if (!isStr(s.section) || !findSection(src, book, s.section)) errs.push(`${sat}: unknown ${book === "sb" ? "textbook" : "Zhao"} section ${String(s.section)}`);
      if (!isStr(s.title) || !strArr(s.concepts) || !s.concepts.every((c) => conceptIds.has(c) && sameSide(l.unit, c))) errs.push(`${sat}: title and known same-side concepts required`);
      if (!Array.isArray(s.layers) || s.layers.length === 0) errs.push(`${sat}: needs at least one layer`);
      else
        s.layers.forEach((ly, k) => {
          if (!oneOf(LAYERS, ly.layer) || !isStr(ly.body)) errs.push(`${sat}.layers[${k}] needs a known layer and a body`);
          for (const r of ly.refs ?? []) if (!refIds.has(r)) errs.push(`${sat}.layers[${k}] refers to unknown item ${r}`);
        });
      errs.push(...validateSourceList(s.sources, `${sat}.sources`, src, l.unit));
    });
  });

  const seenQ = new Set<string>();
  const basisIds = new Map<string, string>(); // id → unit, for provenance bases
  for (const x of [...b.equations, ...b.algorithms, ...b.examples, ...b.figures]) if (isStr(x?.id)) basisIds.set(x.id, x.unit);
  b.questionFiles.forEach((f, i) => errs.push(...validateQuestionFile(f, src, units, conceptIds, conceptUnit, ctx, `questions[${i}] (${f?.unit})`, seenQ, basisIds)));
  // Related questions are checked once every file has been read.
  const all = b.questionFiles.flatMap((f) => (Array.isArray(f?.questions) ? f.questions : []));
  const qUnit = new Map(all.filter((q) => isStr(q?.id)).map((q) => [q.id, q.unit]));
  for (const q of all) {
    if (q?.related === undefined) continue;
    if (!strArr(q.related)) errs.push(`question ${q.id}: related must be a string array`);
    else
      for (const r of q.related) {
        if (r === q.id) errs.push(`question ${q.id}: lists itself as related`);
        else if (!qUnit.has(r)) errs.push(`question ${q.id}: related names unknown question ${r}`);
        else if (isSupplementaryUnit(qUnit.get(r)!) !== isSupplementaryUnit(q.unit)) errs.push(`question ${q.id}: related question ${r} is on the other side of the core/supplementary line`);
      }
  }
  return errs;
}

/** "Exercise 4.1", "§2.4" or a content item id. Returns an error message, or null if the basis is valid. */
function checkBasis(b: unknown, unit: string, src: Sources, basisIds: Map<string, string>): string | null {
  if (!isStr(b)) return "basis entries must be strings";
  const ex = /^Exercise (\d+\.\d+)$/.exec(b);
  if (ex) {
    const e = src.sb.exercises.find((x) => x.id === ex[1]);
    if (!e) return `${b} is not an exercise in the April 2015 draft`;
    if (e.placeholder) return `${b} is a placeholder in the draft ("There is no exercise ${e.id}")`;
    return isSupplementaryUnit(unit) ? `${b}: supplementary questions may not be based on textbook exercises` : null;
  }
  const sec = /^§(.+)$/.exec(b);
  if (sec) {
    const book = isSupplementaryUnit(unit) ? "zhao" : "sb";
    return findSection(src, book, sec[1]) ? null : `${b} is not a ${book === "sb" ? "textbook" : "Zhao"} section`;
  }
  if (!basisIds.has(b)) return `basis ${b} is not an exercise, a section or a known equation/algorithm/example/figure`;
  return isSupplementaryUnit(basisIds.get(b)!) === isSupplementaryUnit(unit) ? null : `basis ${b} is on the other side of the core/supplementary line`;
}

/** The textbook sources of a question must include the printed page of an exercise it is based on. */
function citesPage(sources: unknown, chapter: string, page: number): boolean {
  return Array.isArray(sources) && sources.some((s) => isObj(s) && s.kind === "textbook" && s.chapter === chapter && pair(s.printedPages) && s.printedPages[0] <= page && page <= s.printedPages[1]);
}

function validateProvenance(q: Obj, unit: string, src: Sources, basisIds: Map<string, string>, at: string): string[] {
  const p = q.provenance;
  if (!isObj(p) || !oneOf(PROVENANCE_KINDS, p.kind)) return [`${at} provenance needs a kind: ${PROVENANCE_KINDS.join(", ")}`];
  if (q.adaptedFrom !== undefined) return [`${at} adaptedFrom was replaced by provenance`];
  const sup = isSupplementaryUnit(unit);
  if (sup !== (p.kind === "supplementary")) return [`${at} provenance must be "supplementary" exactly when the unit is supplementary`];
  const errs: string[] = [];
  const bases = p.kind === "textbook-exercise" ? [`Exercise ${String(p.exercise)}`] : p.basis;
  if (p.kind === "textbook-derived" && !(Array.isArray(bases) && bases.length > 0)) return [`${at} textbook-derived provenance needs at least one basis`];
  if (bases !== undefined && !Array.isArray(bases)) return [`${at} provenance basis must be an array`];
  for (const b of bases ?? []) {
    const e = checkBasis(b, unit, src, basisIds);
    if (e) errs.push(`${at} provenance: ${e}`);
    const m = isStr(b) ? /^Exercise (\d+\.\d+)$/.exec(b) : null;
    const ex = m && src.sb.exercises.find((x) => x.id === m[1]);
    if (ex && !ex.placeholder && !citesPage(q.sources, ex.chapter, ex.page)) errs.push(`${at} sources must cite the page of Exercise ${ex.id} (printed p. ${ex.page})`);
  }
  if (p.kind === "textbook-exercise") {
    if (!isStr(p.exercise)) errs.push(`${at} textbook-exercise provenance needs the exercise number`);
    else if (!p.exercise.startsWith(`${Number(unit.slice(2))}.`)) errs.push(`${at} Exercise ${p.exercise} belongs to another chapter`);
  }
  return errs;
}

/** References resolve and prerequisites form no cycle. */
export function validateConceptGraph(concepts: Concept[]): string[] {
  const errs: string[] = [];
  const byId = new Map(concepts.map((c) => [c.id, c]));
  for (const c of concepts)
    for (const f of ["prereqs", "related"] as const)
      for (const r of c[f] ?? []) {
        if (!byId.has(r)) errs.push(`concept ${c.id}: ${f} names unknown concept ${r}`);
        if (r === c.id) errs.push(`concept ${c.id}: lists itself in ${f}`);
      }
  const state = new Map<string, 1 | 2>();
  const visit = (id: string, path: string[]): void => {
    if (state.get(id) === 2) return;
    if (state.get(id) === 1) {
      errs.push(`prerequisite cycle: ${[...path.slice(path.indexOf(id)), id].join(" → ")}`);
      return;
    }
    state.set(id, 1);
    for (const p of byId.get(id)?.prereqs ?? []) if (byId.has(p)) visit(p, [...path, id]);
    state.set(id, 2);
  };
  for (const c of concepts) visit(c.id, []);
  return errs;
}

export function validateQuestionFile(
  data: unknown, src: Sources, units: Set<string>, concepts: Set<string>, conceptUnit: Map<string, string>,
  ctx: ValidationContext, label: string, seen: Set<string>, basisIds: Map<string, string> = new Map(),
): string[] {
  if (!isObj(data)) return [`${label}: not an object`];
  if (!isStr(data.unit) || !units.has(data.unit)) return [`${label}: unknown unit ${String(data.unit)}`];
  if (!Array.isArray(data.questions)) return [`${label}: questions must be an array`];
  const errs: string[] = [];
  const unit = data.unit;
  data.questions.forEach((q: unknown, i) => {
    const at = `${label} q[${i}]`;
    if (!isObj(q)) return errs.push(`${at} not an object`);
    if (!isStr(q.id) || !new RegExp(`^${unit}-q\\d{3}$`).test(q.id)) errs.push(`${at} id must look like ${unit}-q001`);
    else if (seen.has(q.id)) errs.push(`${at} duplicate id ${q.id}`);
    else seen.add(q.id);
    if (q.unit !== unit) errs.push(`${at} unit differs from the file`);
    if (!oneOf(QUESTION_TYPES, q.type)) return errs.push(`${at} bad type`);
    // Section mapping: a section of this unit's chapter (textbook for core, the attached Zhao chapters for supplementary), or null.
    if (q.section !== null) {
      const sup = isSupplementaryUnit(unit);
      const sec = isStr(q.section) ? findSection(src, sup ? "zhao" : "sb", q.section) : undefined;
      const chapterOk = isStr(q.section) && (sup ? true : q.section.startsWith(`${Number(unit.slice(2))}.`));
      if (!sec || !chapterOk) errs.push(`${at} section must be null or a ${sup ? "Zhao" : "textbook"} section of this unit's chapter (got ${String(q.section)})`);
    }
    errs.push(...validateProvenance(q, unit, src, basisIds, at));
    if ((SELF_MARKED_TYPES as readonly string[]).includes(q.type)) {
      const r = q.rubric;
      if (!Array.isArray(r) || r.length === 0 || !r.every((x) => isObj(x) && isStr(x.point) && isNum(x.marks) && x.marks > 0)) errs.push(`${at} ${q.type} needs a rubric of marking points with positive marks`);
      else if (isNum(q.marks) && Math.abs(r.reduce((s, x) => s + (x.marks as number), 0) - q.marks) > 1e-9) errs.push(`${at} rubric marks must add up to the question's marks`);
    } else if (q.rubric !== undefined) errs.push(`${at} rubric is only for derivation and short-answer questions`);
    if (q.optionNotes !== undefined || (q.reviewed === true && (q.type === "mcq" || q.type === "multi"))) {
      const n = q.optionNotes;
      if (q.type !== "mcq" && q.type !== "multi") errs.push(`${at} optionNotes are only for mcq and multi`);
      else if (!(Array.isArray(n) && Array.isArray(q.options) && n.length === q.options.length && n.every(isStr))) errs.push(`${at} reviewed mcq/multi questions need one optionNote per option, saying why it is right or wrong`);
    }
    if (!oneOf(QUESTION_CATEGORIES, q.category)) errs.push(`${at} bad category`);
    if (![1, 2, 3, 4].includes(q.difficulty as number)) errs.push(`${at} difficulty must be 1–4`);
    if (!isNum(q.marks) || q.marks <= 0) errs.push(`${at} marks must be positive`);
    if (!isStr(q.stem) || !isStr(q.explanation)) errs.push(`${at} stem and explanation required`);
    if (!Array.isArray(q.solution) || q.solution.length === 0 || !q.solution.every(isStr)) errs.push(`${at} solution needs at least one step`);
    if (typeof q.reviewed !== "boolean") errs.push(`${at} reviewed must be boolean`);
    if (!strArr(q.concepts) || q.concepts.length === 0) errs.push(`${at} needs at least one concept`);
    else
      for (const c of q.concepts) {
        if (!concepts.has(c)) errs.push(`${at} unknown concept ${c}`);
        else if (isSupplementaryUnit(unit) !== isSupplementaryUnit(conceptUnit.get(c)!)) errs.push(`${at} concept ${c} is on the other side of the core/supplementary line`);
      }
    const opts = q.options;
    const hasOpts = Array.isArray(opts) && opts.length >= 2 && opts.every(isStr) && new Set(opts).size === opts.length;
    switch (q.type) {
      case "mcq":
        if (!hasOpts) errs.push(`${at} needs 2+ distinct options`);
        else if (!(isInt(q.answer) && q.answer >= 0 && q.answer < opts.length)) errs.push(`${at} mcq answer must be an option index`);
        break;
      case "multi":
        if (!hasOpts) errs.push(`${at} needs 2+ distinct options`);
        else if (!(Array.isArray(q.answer) && q.answer.length > 0 && new Set(q.answer).size === q.answer.length && q.answer.every((a) => isInt(a) && a >= 0 && a < opts.length)))
          errs.push(`${at} multi answer must be distinct option indices`);
        break;
      case "ordering":
        if (!hasOpts || opts.length < 3) errs.push(`${at} ordering needs 3+ distinct steps`);
        break;
      case "true-false":
        if (typeof q.answer !== "boolean") errs.push(`${at} true-false answer must be boolean`);
        break;
      case "derivation":
      case "short-answer":
        if (!isStr(q.answer)) errs.push(`${at} ${q.type} needs a model answer`);
        break;
      case "numeric":
      case "multi-numeric": {
        const parts = q.parts;
        if (!Array.isArray(parts) || (q.type === "numeric" ? parts.length !== 1 : parts.length < 2)) errs.push(`${at} needs ${q.type === "numeric" ? "exactly one part" : "two or more parts"}`);
        else parts.forEach((p: unknown, j) => {
          if (!isObj(p) || !isStr(p.label) || !isNum(p.answer) || !isNum(p.tolerance) || p.tolerance < 0) errs.push(`${at}.parts[${j}] needs label, answer and tolerance ≥ 0`);
        });
        // Every numerical answer key is recomputed by an automated check.
        if (!(isObj(q.verification) && q.verification.method === "computed")) errs.push(`${at} numeric answers must be verified by a computed check`);
        break;
      }
    }
    if (opts !== undefined && !["mcq", "multi", "ordering"].includes(q.type)) errs.push(`${at} options only allowed for mcq, multi and ordering`);
    errs.push(...validateSourceList(q.sources, `${at}.sources`, src, unit), ...validateVerification(q.verification, at, ctx.checks, false));
  });
  return errs;
}
